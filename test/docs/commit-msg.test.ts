import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";

const SCRIPT = resolve(import.meta.dirname, "../../scripts/check-commit-msg.sh");

/** Runs the commit-msg hook on a message and returns its exit status and what it said. */
function check(message: string): { status: number | null; stderr: string } {
  const dir = mkdtempSync(join(tmpdir(), "commit-msg-"));
  try {
    const file = join(dir, "MESSAGE");
    writeFileSync(file, message);
    const run = spawnSync("sh", [SCRIPT, file], { encoding: "utf8" });
    return { status: run.status, stderr: run.stderr };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

describe("scripts/check-commit-msg.sh", () => {
  it("accepts an ordinary message", () => {
    expect(check("Add the ledger\n\nEntries are keyed by the business fact.\n").status).toBe(0);
  });

  it("refuses a trailer line, whatever its case", () => {
    for (const trailer of ["Co-authored-by: A <a@example.invalid>", "signed-off-by: A <a@example.invalid>", "Reviewed-by : A", "Assisted-by: a tool", "GENERATED-BY: a tool"]) {
      const result = check(`Add the ledger\n\n${trailer}\n`);
      expect(result.status, trailer).toBe(1);
      expect(result.stderr).toContain(trailer);
    }
  });

  it("refuses a note that says the message or the change was generated", () => {
    expect(check("Add the ledger\n\nGenerated by a tool.\n").status).toBe(1);
    expect(check("Add the ledger, generated with a script\n").status).toBe(1);
  });

  it("does not read comment lines, and does not mistake a trailer name inside a sentence for a trailer", () => {
    expect(check("Add the ledger\n# Co-authored-by: nobody\n# generated by git\n").status).toBe(0);
    expect(check("Add the ledger\n\nThe co-authored-by line is not wanted here.\n").status).toBe(0);
  });
});
